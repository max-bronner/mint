#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Quat {
    pub x: f32,
    pub y: f32,
    pub z: f32,
    pub w: f32,
}

impl Default for Quat {
    fn default() -> Self {
        Self {
            x: 0.0,
            y: 0.0,
            z: 0.0,
            w: 1.0,
        }
    }
}

impl Element for Quat {
    const SIZE: usize = 16;
    fn read(r: &mut Reader<'_>) -> crate::Result<Self> {
        Ok(Self {
            x: r.f32()?,
            y: r.f32()?,
            z: r.f32()?,
            w: r.f32()?,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_ids_are_named_and_unknown_ones_are_not() {
        assert_eq!(ChunkType::MESH_HEADER3.name(), Some("MESH_HEADER3"));
        assert_eq!(ChunkType::HLOD.0, 0x700);
        assert_eq!(ChunkType::HIERARCHY.0, 0x100);
        assert_eq!(ChunkType(0xDEAD_BEEF).name(), None);
        assert_eq!(format!("{}", ChunkType(0xDEAD_BEEF)), "0xDEADBEEF");
    }

    #[test]
    fn the_two_persistence_class_ids_stay_unnamed() {
        assert_eq!(ChunkType(0x1649_0430).name(), None);
        assert_eq!(ChunkType(0x1649_0450).name(), None);
    }

    #[test]
    fn identity_quaternion_is_the_default() {
        assert_eq!(
            Quat::default(),
            Quat {
                x: 0.0,
                y: 0.0,
                z: 0.0,
                w: 1.0
            }
        );
    }
}
