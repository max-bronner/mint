fn placed() -> (Simulation<RotwkRules>, Ids, Entity, Entity) {
    let doc =
        mint_sage_ini::Document::parse("t.ini", DATA, &mint_sage_ini::BlockTable::corpus_path())
            .unwrap();
    assert!(doc.is_balanced(), "{:?}", doc.diagnostics());
    let (data, _) = crate::combat::game_data_from_documents(&[doc], 0, std::time::Instant::now());
    let names = ["Bombardier", "Standee"].map(str::to_owned);
    let (kinds, missing) = KindTable::closure(&data, &names);
    assert!(missing.is_empty(), "missing from the closure: {missing:?}");
    let kinds = Arc::new(kinds);
    let production = kinds.production(&data);
    let spawn = |name: &str, at: Vec2, owner: PlayerId| {
        kinds
            .spawn(
                &data.combat,
                kinds.kind(name).unwrap(),
                at,
                Facing::EAST,
                owner,
            )
            .unwrap()
    };
    let spawns = vec![
        spawn("Bombardier", Vec2::new(300.0, 300.0), PLAYER),
        spawn("Standee", Vec2::new(400.0, 300.0), OTHER),
    ];
    let passability = Passability::build(&flat_map(96, 96), 5.0 / 128.0).unwrap();
    let rules = RotwkRules::new(passability, spawns)
        .with_combat(data.combat.clone())
        .with_guard_ranges(data.guard_ranges)
        .with_construction(Arc::clone(&kinds), production)
        .with_teams(vec![None, None])
        .with_map_players(
            2,
            vec!["Creeps".to_owned()],
            vec![crate::alliance::MapRelations {
                universal_hostile: true,
                ..crate::alliance::MapRelations::default()
            }],
        );
    let simulation = Simulation::new(5, rules).unwrap();
    let ids = simulation.rules().ids().unwrap();
    let entities = simulation
        .state()
        .store(ids.body)
        .unwrap()
        .entities()
        .to_vec();
    let (shooter, standee) = (entities[0], entities[1]);
    (simulation, ids, shooter, standee)
}

#[test]
fn a_loose_units_first_attack_order_is_not_already_attacking() {
    let (mut simulation, _ids, shooter, standee) = placed();
    simulation
        .submit(
            PLAYER,
            RotwkCommand::SetSelection {
                replace: true,
                units: vec![shooter],
            },
        )
        .unwrap();
    simulation
        .submit(PLAYER, RotwkCommand::AttackObject { target: standee })
        .unwrap();
    simulation.tick().unwrap();
    let frame = Frame::new(simulation.frame().get() - 1);
    let events = simulation
        .rules()
        .voice_events(simulation.state(), frame)
        .to_vec();
    let attack = events
        .iter()
        .find(|event| event.kind == crate::voice::VoiceKind::Attack)
        .expect("the order fires an attack voice event");
    assert!(
        !attack.was_attacking,
        "a unit with no standing order was already ATTACKING"
    );
}
