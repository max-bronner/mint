#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct Vec3 {
    pub x: f32,
    pub y: f32,
    pub z: f32,
}

impl Element for Vec3 {
    const SIZE: usize = 12;
    fn read(r: &mut Reader<'_>) -> crate::Result<Self> {
        Ok(Self {
            x: r.f32()?,
            y: r.f32()?,
            z: r.f32()?,
        })
    }
}

