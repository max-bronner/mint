use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let mut failed = false;
    failed |= !write(&dir.join("golden_f32.rs"), &f32_file());
    failed |= !write(&dir.join("golden_f64.rs"), &f64_file());
    if failed {
        std::process::exit(1);
    }
}

fn write(path: &Path, contents: &str) -> bool {
    match std::fs::write(path, contents) {
        Ok(()) => {
            println!("wrote {}", path.display());
            true
        }
        Err(e) => {
            eprintln!("could not write {}: {e}", path.display());
            false
        }
    }
}

fn header(width: &str) -> String {
    format!(
        "//! @generated by `cargo run -p mint-math --example record-goldens`. Do not edit.\n\
         //!\n\
         //! Golden bit patterns for the deterministic `{width}` transcendentals.\n\
         //!\n\
         //! Every expected value was **recorded from this implementation**, built\n\
         //! against the exact `libm` version pinned in the workspace manifest, on\n\
         //! x86-64 Windows. They are not independently derived reference results.\n\
         //! They exist to fail loudly when a result changes, because a changed\n\
         //! result invalidates every replay, every saved game and every recorded\n\
         //! simulation state hash - and does so silently otherwise.\n\
         //!\n\
         //! A failure here means one of: the pinned `libm` version moved, the\n\
         //! features it is built with changed, the target changed, or someone\n\
         //! edited a wrapper. It does not mean the table needs regenerating.\n\
         //!\n\
         //! NaN results assert `is_nan()` rather than an exact bit pattern. The\n\
         //! payload and sign of a NaN are not specified by IEEE-754 and x86-64 and\n\
         //! ARM64 genuinely differ, so an exact comparison here would be a test\n\
         //! that fails on a correct port.\n\n"
    )
}

